/**
 * Emits src/noviraFullCatalog.generated.js with explicit imports (no import-glob).
 * Run from repo root: node scripts/generate-novira-full-catalog.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const demoCatalog = path.join(root, 'demo/src/catalog');

const files = [];

function walk(dir, base = '') {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const rel = path.posix.join(base.replace(/\\/g, '/'), e.name);
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, rel);
    else if (e.name === 'planner-element.jsx') files.push(rel);
  }
}

walk(demoCatalog);
files.sort();

const byGroup = { areas: [], lines: [], holes: [], items: [] };
for (const f of files) {
  const segs = f.split('/').filter(Boolean);
  const group = segs[0];
  const key = segs[1];
  if (!byGroup[group]) continue;
  byGroup[group].push({
    importPath: `../demo/src/catalog/${f}`.replace(/\\/g, '/'),
    key,
    varName: `${group}_${key}`.replace(/[^a-zA-Z0-9_]/g, '_'),
  });
}

const lines = [];
lines.push('/* eslint-disable */');
lines.push('/* Auto-generated by scripts/generate-novira-full-catalog.mjs — do not edit by hand */');
lines.push("import Catalog from './catalog/catalog';");
lines.push('');

for (const g of ['areas', 'lines', 'holes', 'items']) {
  for (const x of byGroup[g]) {
    lines.push(`import ${x.varName} from '${x.importPath}';`);
  }
}
lines.push('');

for (const g of ['areas', 'lines', 'holes', 'items']) {
  const parts = byGroup[g].map((x) => `  ${JSON.stringify(x.key)}: (${x.varName}.default != null ? ${x.varName}.default : ${x.varName})`);
  lines.push(`const _${g} = {`);
  lines.push(parts.join(',\n'));
  lines.push('};');
  lines.push('');
}

lines.push('export default function createFullDemoCatalog() {');
lines.push('  const catalog = new Catalog();');
lines.push("  ['areas', 'lines', 'holes', 'items'].forEach((g) => {");
lines.push('    const o = { areas: _areas, lines: _lines, holes: _holes, items: _items }[g];');
lines.push('    Object.keys(o).forEach((k) => catalog.registerElement(o[k]));');
lines.push('  });');
lines.push("  catalog.registerCategory('windows', 'Windows', [_holes['window'], _holes['sash-window'], _holes['venetian-blind-window'], _holes['window-curtain']]);");
lines.push("  catalog.registerCategory('doors', 'Doors', [_holes['door'], _holes['door-double'], _holes['panic-door'], _holes['panic-door-double'], _holes['sliding-door']]);");
lines.push('  return catalog;');
lines.push('}');

const out = path.join(root, 'src/noviraFullCatalog.generated.js');
fs.writeFileSync(out, lines.join('\n') + '\n', 'utf8');
console.log('Wrote', out, `(${files.length} elements)`);
